"""Parseurs PURS pour extraire des crédits depuis les descriptions YouTube.

Deux familles :
- **Topic** (canal « - Topic ») : structuré par le distributeur,
  ``Rôle, Rôle: Nom`` ligne à ligne.
- **Clip** officiel : description LIBRE, motifs fermés FR/EN.
"""

from __future__ import annotations

import re
from typing import TYPE_CHECKING

from src.models.track import Credit, CreditRole
from src.utils.credit_roles import map_role

if TYPE_CHECKING:
    pass

# ── Topic ────────────────────────────────────────────────────────────────────

_TOPIC_IGNORE = {
    "provided to youtube",
    "auto-generated by youtube.",
    "auto-generated by youtube",
}

#: « ℗ Tallac Records », « ℗ 2016 Label », « ℗ & © 2024 : VF Musiques » —
#: mesuré sur A2H (2026-09-22), la 3ᵉ forme entrait telle quelle en Label.
_LABEL_RE = re.compile(r"^℗\s*(?:&\s*©\s*)?(?:\d{4}\s*:?\s*)?(.+?)(?:\s*[-–]\s*\d{4})?$")

#: Clés « X: Y » d'une Topic qui ne sont PAS des crédits (mesuré : « Released
#: on: 2016-06-15 » entrait en Other « 2016-06-15 »).
_TOPIC_NON_CREDIT_KEYS = {"released on", "provided to youtube by", "auto-generated by youtube"}

#: Une ligne qui porte un lien n'est jamais un crédit (« Facebook :
#: https://… », « https://lnk.to/… » : 4 « Other » écrits sur UN morceau).
_URL_RE = re.compile(r"https?://|www\.|//[a-z0-9.-]+\.[a-z]{2,}", re.IGNORECASE)

#: « Composer: D.R » : « droits réservés », la mention d'un auteur INCONNU, pas
#: un nom (mesuré 2026-10-10 : 31 crédits Topic, dont 20 déjà en base).
_NOM_ANONYME = re.compile(r"d\.?\s?r\.?|droits?\s+r[ée]serv[ée]s", re.IGNORECASE)


def _nom_anonyme(name: str) -> bool:
    return bool(_NOM_ANONYME.fullmatch(name.strip()))


def est_description_topic(text: str | None, channel: str | None = None) -> bool:
    """Une description Topic se reconnaît à son canal « … - Topic » ou à sa
    première ligne « Provided to YouTube by … » — pas au genre « audio » de la
    vidéo : un audio posté par le label (Waxx) a une description LIBRE."""
    if channel and channel.strip().lower().endswith("- topic"):
        return True
    return bool(text) and text.lstrip().lower().startswith("provided to youtube")


def parse_description_topic(text: str) -> list[Credit] | None:
    """Parse une description Topic (canal « - Topic »).

    Format attendu (une ligne par crédit) ::

        Rôle, Rôle: Nom
        ℗ 2024 Label

    Rend ``None`` si aucune ligne ``Rôle: Nom`` n'est trouvée (ce n'est
    probablement pas une Topic).
    """
    if not text:
        return None

    credits: list[Credit] = []
    found_role_line = False
    # La ligne qui SUIT « Titre · Artiste » est le titre du DISQUE : avec un
    # deux-points (« The Blueprint 2: The Gift & The Curse », « Old School : Rap
    # français ») elle sortait en crédit Other (14 Topic sur 745, 2026-10-10).
    apres_titre = False

    for raw_line in text.splitlines():
        line = raw_line.strip()
        if not line:
            continue
        if line.lower() in _TOPIC_IGNORE:
            continue

        m_label = _LABEL_RE.match(line)
        if apres_titre:
            apres_titre = False
            if not m_label and not line.lower().startswith("released on"):
                continue
        if "·" in line:
            apres_titre = True
            continue
        if m_label:
            credits.append(
                Credit(name=m_label.group(1).strip(), role=CreditRole.LABEL, source="youtube_topic")
            )
            found_role_line = True
            continue

        if "·" in line or ":" not in line or _URL_RE.search(line):
            continue

        roles_part, _, name = line.partition(":")
        name = name.strip()
        if not name or roles_part.strip().lower() in _TOPIC_NON_CREDIT_KEYS:
            continue
        if _nom_anonyme(name):
            found_role_line = True
            continue

        role_labels = [r.strip() for r in roles_part.split(",") if r.strip()]
        if not role_labels:
            continue

        found_role_line = True
        for label in role_labels:
            credits.append(Credit(name=name, role=map_role(label), source="youtube_topic"))

    return credits if found_role_line else None


# ── Clip ─────────────────────────────────────────────────────────────────────

_CLIP_PATTERNS: list[tuple[re.Pattern[str], CreditRole]] = [
    (
        re.compile(
            r"(?:Prod(?:uit|\.)?|Produc(?:tion|ed))\s*(?:(?:by|par)\s*:?\s*|:\s*)(.+)",
            re.IGNORECASE,
        ),
        CreditRole.PRODUCER,
    ),
    # « Prod A2H », « (Prod Dtweezer) », « Prod: X » — la forme NUE du rap FR
    # (mesuré sur A2H : 3 producteurs sur 16 descriptions, tous manqués). « Prod »
    # est un MOT : sans limite, « Producer: X » rendait le nom « ucer: X ».
    (
        re.compile(r"(?:^|\()Prod\b\.?\s*:?\s*(?!by\b|par\b)([^)\n]+)", re.IGNORECASE),
        CreditRole.PRODUCER,
    ),
    (re.compile(r"Beat\s+by\s+(.+)", re.IGNORECASE), CreditRole.PRODUCER),
    (
        re.compile(
            r"(?:Réalis(?:é|ation)|Direct(?:ed|ion))\s+(?:par\s+|by\s+|:\s*)(.+)", re.IGNORECASE
        ),
        CreditRole.VIDEO_DIRECTOR,
    ),
    # « Real: Boilerhum », « Réalisation vidéo : Ledok », « Réal. : X »
    (
        re.compile(r"^R[ée]al(?:isation|\.)?(?:\s+vid[ée]o)?\s*:\s*(.+)", re.IGNORECASE),
        CreditRole.VIDEO_DIRECTOR,
    ),
    (
        re.compile(r"Mix(?:é|ing|ed)?\s+(?:par\s+|by\s+|:\s*)(.+)", re.IGNORECASE),
        CreditRole.MIXING_ENGINEER,
    ),
    (
        re.compile(r"Master(?:isé|ing|ed)?\s+(?:par\s+|by\s+|:\s*)(.+)", re.IGNORECASE),
        CreditRole.MASTERING_ENGINEER,
    ),
    (re.compile(r"(?:Écrit|Written)\s+(?:par\s+|by\s+)(.+)", re.IGNORECASE), CreditRole.WRITER),
    (re.compile(r"(?:Lyrics|Paroles)\s*:\s*(.+)", re.IGNORECASE), CreditRole.LYRICIST),
    (
        re.compile(r"Record(?:ed|ing)\s+(?:par\s+|by\s+|:\s*)(.+)", re.IGNORECASE),
        CreditRole.RECORDING_ENGINEER,
    ),
]

#: « x » sépare deux noms seulement entre deux espaces : « Apex Martin » était
#: coupé en « Ape » et « Martin » (Travis Scott, Fire).
_NAME_SPLIT_RE = re.compile(r"\s*[,&]\s+|\s+x\s+|\s+(?:et|and|feat\.?)\s+", re.IGNORECASE)
_NAME_CLEAN_RE = re.compile(r"[(\[@#].*$")


def _split_names(raw: str) -> list[str]:
    """Découpe une chaîne de noms séparés par virgule, &, x, et, and."""
    parts = _NAME_SPLIT_RE.split(raw.strip())
    result = []
    for p in parts:
        cleaned = _NAME_CLEAN_RE.sub("", p).strip(" :-–").rstrip(".")
        if cleaned.endswith(")") and "(" not in cleaned:  # « (Prod. by RZA) »
            cleaned = cleaned[:-1].rstrip()
        # « Prod : https://youtu.be/… » (Jazzy Bazz, 1989 Freestyle) : le beat
        # est un LIEN, pas un nom — il sortait en Producer.
        if cleaned and len(cleaned) > 1 and not _URL_RE.search(cleaned):
            result.append(cleaned)
    return result


#: Postes de l'ÉQUIPE DE TOURNAGE dont l'intitulé contient « production »,
#: « réalisation » ou « direction » : « Directeur de Production : Nicholas Kanel »
#: sortait en PRODUCER sur A2H « Le cœur des filles » (2026-09-24). Une ligne qui
#: les nomme n'est jamais lue par les motifs musicaux.
_POSTES_DE_TOURNAGE = re.compile(
    r"\b(?:directeur|directrice|chef|chargée?|assistante?|régisseu(?:r|se)|coordinat(?:eur|rice)|"
    r"line|unit|executive)\b[^:]*\b(?:de\s+)?(?:production|prod)\b",
    re.IGNORECASE,
)


#: Production qui n'est pas celle du MORCEAU : coproduction, post-production,
#: production exécutive (« Prod exe sous-marine : Splashprod », « Production
#: exécutive : 386 Lab »).
_PRODUCTION_NON_MUSICALE = re.compile(
    r"\b(?:co-?production|post[- ]?prod(?:uction)?|prod(?:uction)?\.?\s*ex[ée]c?(?:utive)?"
    r"|ex[ée]cutive)\b",
    re.IGNORECASE,
)
#: « Production : Solab », « Production - Beaucartel » : la boîte qui a tourné le clip.
_LIGNE_PRODUCTION = re.compile(r"\bproduction\s*[:\-–]", re.IGNORECASE)
#: L'équipe de TOURNAGE est créditée dans la description : « Produit par » /
#: « Produced by » y désigne le producteur de la vidéo, sauf si la ligne parle
#: de musique.
_EQUIPE_DE_TOURNAGE = re.compile(
    r"\b(?:r[ée]alis[ée]e?|r[ée]alisation|directed|director|dop|chef op\w*|montage|"
    r"[ée]talonnage|cam[ée]ra|steadicam|stylis\w*|maquillage|make.?up|gaffer|editor|"
    r"edited by|colorist|vfx)\b",
    re.IGNORECASE,
)
_PRODUIT_PAR = re.compile(r"\b(?:produced by|produit par|production by)\b", re.IGNORECASE)
_MOT_DE_MUSIQUE = re.compile(
    r"\b(?:compos\w*|beat|instru\w*|son|music|musique|song|morceau|titre|mix\w*|master\w*"
    r"|enregistr\w*|recorded)\b",
    re.IGNORECASE,
)
#: Un nom de SOCIÉTÉ de production vidéo, pas un beatmaker.
_SOCIETE = re.compile(
    r"(?:prod\b|prods\b|production|studio|films?\b|\blab\b|pictures|m[ée]dia|agency|collective)",
    re.IGNORECASE,
)
#: De la prose ou un débris, pas un nom (« has all of the original verses from
#: Travis », « enregistré », « 2020 », « Asst. / Runner: … »).
_PROSE = re.compile(
    r"\b(?:the|was|is|are|of|with|from|later|original|verses?|leak(?:ed)?|version|"
    r"track(?:list)?|enregistr\w*|mix(?:ed)?|scratch|runner|asst\.?|assistant|which|this|"
    r"that|en|et|le|la|les|des|du|une?|par|by|pour)\b|\d{4}",
    re.IGNORECASE,
)


def _producteur_plausible(nom: str) -> bool:
    mots = nom.split()
    return (
        1 <= len(mots) <= 4
        and (nom[:1].isalnum() or nom[:1] == "$")  # « $herwood »
        and not nom.isdigit()
        and not _SOCIETE.search(nom)
        and not _PROSE.search(nom)
    )


def parse_description_clip(text: str) -> list[Credit]:
    """Parse une description de clip officiel avec des motifs fermés FR/EN.

    Le PRODUCTEUR d'un clip est souvent celui de la vidéo : mesuré le
    2026-10-13 sur 8 226 descriptions réelles contre Genius, Discogs et les
    Topic, 949 justes pour 969 faux. Écartés : la production non musicale
    (coproduction, post-production, exécutive), les lignes « Production : »,
    « Produit par / Produced by » quand l'équipe de tournage est créditée, les
    noms de société et la prose — 743 justes pour 258 faux, dont une bonne part
    sont de vrais producteurs que la référence ignore (« Prod : KobéBeats »)."""
    if not text:
        return []

    tournage = bool(_EQUIPE_DE_TOURNAGE.search(text))
    credits: list[Credit] = []
    for line in text.splitlines():
        line = line.strip()
        if not line or _POSTES_DE_TOURNAGE.search(line):
            continue
        for pattern, role in _CLIP_PATTERNS:
            m = pattern.search(line)
            if not m:
                continue
            if role is CreditRole.PRODUCER and (
                _PRODUCTION_NON_MUSICALE.search(line)
                or _LIGNE_PRODUCTION.search(line)
                or (tournage and _PRODUIT_PAR.search(line) and not _MOT_DE_MUSIQUE.search(line))
            ):
                continue  # la ligne peut nommer un autre poste (« … / Mastering : X »)
            for name in _split_names(m.group(1)):
                if role is CreditRole.PRODUCER and not _producteur_plausible(name):
                    continue
                credits.append(Credit(name=name, role=role, source="youtube_clip"))
            break
    return credits
