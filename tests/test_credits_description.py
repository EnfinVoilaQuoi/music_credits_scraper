# Topic réelle (Diam's, relevée le 2026-10-10) : le disque porte un deux-points
# et l'auteur est inconnu (« D.R », droits réservés).
DIAMS_TOPIC = """\
Provided to YouTube by Wagram

Avec des si on mettrait Paris en bouteille · Diam's · Antilop Sa

Old School : Rap français

℗ Wagram Music

Released on: 2021-03-26

Composer: M. Georgiades
Composer: D.R
Lyricist: Droits Réservés

Auto-generated by YouTube.
"""


class TestTopicDisqueEtAnonymes:
    def test_le_titre_du_disque_n_est_pas_un_credit(self):
        noms = [(c.name, c.role.value) for c in parse_description_topic(DIAMS_TOPIC)]
        assert noms == [("Wagram Music", "Label"), ("M. Georgiades", "Composer")]

    def test_le_label_juste_apres_le_titre_reste_lu(self):
        texte = "Provided to YouTube by X\n\nT · A\n\n℗ 2016 Label\n\nProducer: Tysko\n"
        assert [(c.name, c.role.value) for c in parse_description_topic(texte)] == [
            ("Label", "Label"),
            ("Tysko", "Producer"),
        ]

    def test_seuls_des_anonymes_reste_une_topic(self):
        """« Composer: Dr » seul : la description est bien une Topic (pas `None`),
        elle ne nomme simplement personne."""
        texte = "Provided to YouTube by X\n\nT · A\n\nDisque\n\nComposer: Dr\nLyricist: Dr\n"
        assert parse_description_topic(texte) == []


class TestClipDecoupage:
    """Défauts mécaniques relevés sur les descriptions réelles (2026-10-10)."""

    def test_par_suivi_de_deux_points(self):
        (c,) = parse_description_clip("Produit Par : Banque De Sons")
        assert (c.name, c.role) == ("Banque De Sons", CreditRole.PRODUCER)

    def test_prod_est_un_mot(self):
        assert [c.name for c in parse_description_clip("Producers: Ye")] == []
        assert [c.name for c in parse_description_clip("Production: @maximeeegrt")] == []
        assert [c.name for c in parse_description_clip("Produced by: Hitmaka")] == ["Hitmaka"]

    def test_x_separe_seulement_entre_espaces(self):
        assert [c.name for c in parse_description_clip("prod. Apex Martin")] == ["Apex Martin"]
        assert [c.name for c in parse_description_clip("Prod : Pinkman x Uraken")] == [
            "Pinkman",
            "Uraken",
        ]

    def test_parenthese_fermante_orpheline(self):
        assert [c.name for c in parse_description_clip("2. Raw (Prod. by RZA)")] == ["RZA"]
